# Quasilinear schedule (mirrors src/quasilinear.c exactly)
# ---------------------------------------------------------------------------
def octonion_cross(e: Emitter, o_r: Ptr, o_i: Ptr, x_r: Ptr, x_i: Ptr,
                   y_r: Ptr, y_i: Ptr) -> None:
    """Emit C_3 using four sparse images of the three-dimensional cross."""

    def add(a, b):
        return (e.add(a[0], b[0]), e.add(a[1], b[1]))

    def sub(a, b):
        return (e.sub(a[0], b[0]), e.sub(a[1], b[1]))

    def times_i(a):
        return (e.neg(a[1]), a[0])

    def half(a):
        return (e.half(a[0]), e.half(a[1]))

    def maps(real, imag):
        x1, x2, x3, h, y1, y2, y3 = [
            (rd(real, i), rd(imag, i)) for i in range(1, 8)]
        p = (h[1], e.neg(h[0]))  # -iota h
        z = add(x1, p)
        b, r = add(x2, times_i(y2)), sub(x2, times_i(y2))
        c, s = add(x3, times_i(y3)), sub(x3, times_i(y3))
        triples = [(x1, y1, p), (add(b, s), sub(r, c), p),
                   (add(z, times_i(y1)), b, c),
                   (sub(z, times_i(y1)), r, s)]
        p_sum = e.add(*p)
        return [([v[0] for v in t], [v[1] for v in t],
                 [p_sum if k < 2 and j == 2 else e.add(*v)
                  for j, v in enumerate(t)]) for k, t in enumerate(triples)]

    def cross(a, b):
        return [e.sub(e.mul(a[i], b[j]), e.mul(a[j], b[i]))
                for i, j in ((1, 2), (2, 0), (0, 1))]

    results = []
    for x, y in zip(maps(x_r, x_i), maps(y_r, y_i), strict=True):
        p, q, w = [cross(a, b) for a, b in zip(x, y, strict=True)]
        results.append([(e.sub(a, b), e.sub(e.sub(c, a), b))
                        for a, b, c in zip(p, q, w, strict=True)])
    (a1, b1, c1), (a2, b2, c2), (a3, b3, c3), (a4, b4, c4) = results
    t, u = add(a3, a4), sub(a3, a4)
    v = add(c2, t)
    d1, d2 = add(a2, b3), add(b2, b4)
    e1, e2 = sub(c3, b2), add(a2, c4)
    ih = times_i(half(v))
    outputs = [sub(half(t), times_i(a1)), half(add(d1, d2)),
               half(add(e1, e2)), sub((e.neg(ih[0]), e.neg(ih[1])), c1),
               times_i(sub(half(u), b1)), times_i(half(sub(d1, d2))),
               times_i(half(sub(e1, e2)))]
    wr(o_r, 0, "0.0")
    wr(o_i, 0, "0.0")
    for i, value in enumerate(outputs, 1):
        wr(o_r, i, value[0])
        wr(o_i, i, value[1])


def complex_cross(e: Emitter, o_r: Ptr, o_i: Ptr, x_r: Ptr, x_i: Ptr,
                  y_r: Ptr, y_i: Ptr, dim: int, ws: Ptr) -> None:
    if dim <= 2:
        for i in range(dim):
            wr(o_r, i, "0.0")
            wr(o_i, i, "0.0")
        return
    if dim == 8:
        octonion_cross(e, o_r, o_i, x_r, x_i, y_r, y_i)
        return
    half = dim >> 1
    txr, txi = off(ws, 0), off(ws, half)
    tyr, tyi = off(ws, dim), off(ws, dim + half)
    child = off(ws, 2 * dim)
    gamma = (rd(x_r, half), rd(x_i, half))
    delta = (rd(y_r, half), rd(y_i, half))
    for p in (txr, txi, tyr, tyi):
        wr(p, 0, "0.0")
    for i in range(1, half):
        wr(txr, i, e.sub(rd(x_r, i), rd(x_i, half + i)))
        wr(txi, i, e.add(rd(x_i, i), rd(x_r, half + i)))
        wr(tyr, i, e.sub(rd(y_r, i), rd(y_i, half + i)))
        wr(tyi, i, e.add(rd(y_i, i), rd(y_r, half + i)))
    complex_cross(e, o_r, o_i, txr, txi, tyr, tyi, half, child)
    for i in range(1, half):
        wr(txr, i, e.add(rd(x_r, i), rd(x_i, half + i)))
        wr(txi, i, e.sub(rd(x_i, i), rd(x_r, half + i)))
        wr(tyr, i, e.add(rd(y_r, i), rd(y_i, half + i)))
        wr(tyi, i, e.sub(rd(y_i, i), rd(y_r, half + i)))
    complex_cross(e, off(o_r, half), off(o_i, half), txr, txi, tyr, tyi,
                  half, child)

    def cadd(a, b):
        return (e.add(a[0], b[0]), e.add(a[1], b[1]))

    def csub(a, b):
        return (e.sub(a[0], b[0]), e.sub(a[1], b[1]))

    def local(u, v, s, t, gamma, delta):
        return (e.sub(e.mul(gamma, t), e.mul(delta, s)),
                e.sub(e.mul(s, v), e.mul(t, u)),
                e.sub(e.mul(delta, u), e.mul(gamma, v)))

    def recover(p, q, w):
        return (e.sub(p, q), e.sub(e.sub(w, p), q))

    def chalf(a):
        return (e.half(a[0]), e.half(a[1]))

    gamma_sum, delta_sum = e.add(*gamma), e.add(*delta)
    scalars = [None, None, None]
    for i in range(1, half):
        u = (rd(x_r, i), rd(x_i, i))
        v = (rd(y_r, i), rd(y_i, i))
        s = (rd(x_r, half + i), rd(x_i, half + i))
        t = (rd(y_r, half + i), rd(y_i, half + i))
        plus = (rd(o_r, i), rd(o_i, i))
        minus = (rd(o_r, half + i), rd(o_i, half + i))
        p = local(u[0], v[0], s[0], t[0], gamma[0], delta[0])
        q = local(u[1], v[1], s[1], t[1], gamma[1], delta[1])
        w = local(e.add(*u), e.add(*v), e.add(*s), e.add(*t),
                  gamma_sum, delta_sum)
        first, second = recover(p[0], q[0], w[0]), recover(p[2], q[2], w[2])
        for j, value in enumerate((p[1], q[1], w[1])):
            scalars[j] = value if i == 1 else e.add(scalars[j], value)
        # At level two the child alternating products are identically zero.
        if dim > 4:
            first = cadd(chalf(cadd(plus, minus)), first)
            diff = chalf(csub(plus, minus))
            second = cadd(second, (e.neg(diff[1]), diff[0]))
        wr(o_r, i, first[0])
        wr(o_i, i, first[1])
        wr(o_r, half + i, second[0])
        wr(o_i, half + i, second[1])
    wr(o_r, 0, "0.0")
    wr(o_i, 0, "0.0")
    scalar = recover(*scalars)
    wr(o_r, half, scalar[0])
    wr(o_i, half, scalar[1])


def quasilinear_cross(e: Emitter, out: Ptr, x: Ptr, y: Ptr, dim: int,
                      ws: Ptr) -> None:
    if dim <= 2:
        wr(out, 0, "0.0")
        if dim == 2:
            wr(out, 1, "0.0")
        return
    half = dim >> 1
    gamma = rd(x, half)
    delta = rd(y, half)
    complex_cross(e, out, off(out, half), x, off(x, half), y, off(y, half),
                  half, ws)
    scalar = None
    for i in range(1, half):
        pair = e.sub(e.mul(rd(x, half + i), rd(y, i)),
                     e.mul(rd(y, half + i), rd(x, i)))
        first = e.add(rd(out, i), e.mul(gamma, rd(y, half + i)))
        second = e.sub(e.mul(delta, rd(x, i)), e.mul(gamma, rd(y, i)))
        scalar = pair if i == 1 else e.add(scalar, pair)
        first = e.sub(first, e.mul(delta, rd(x, half + i)))
        second = e.sub(second, rd(out, half + i))
        wr(out, i, first)
        wr(out, half + i, second)
    wr(out, 0, "0.0")
    wr(out, half, scalar)


def reconstruct(e: Emitter, out: Ptr, x: Ptr, y: Ptr, dim: int) -> None:
    alpha = rd(x, 0)
    beta = rd(y, 0)
    if dim == 1:
        wr(out, 0, e.mul(alpha, beta))
        return
    dot = e.mul(rd(x, 1), rd(y, 1))
    for i in range(2, dim):
        dot = e.add(dot, e.mul(rd(x, i), rd(y, i)))
    wr(out, 0, e.sub(e.mul(alpha, beta), dot))
    for i in range(1, dim):
        st = e.add(e.mul(alpha, rd(y, i)), e.mul(beta, rd(x, i)))
        wr(out, i, e.add(rd(out, i), st))


# ---------------------------------------------------------------------------
# Direct schedule: signed coordinate sum with hardcoded basis signs
# ---------------------------------------------------------------------------
def direct_mul(e: Emitter, out: Ptr, x: Ptr, y: Ptr, dim: int) -> None:
    for k in range(dim):
        acc = e.mul(rd(x, 0), rd(y, k))
        for i in range(1, dim):
            j = i ^ k
            term = e.mul(rd(x, i), rd(y, j))
            acc = e.add(acc, term) if sign(dim, i, j) > 0 else e.sub(acc, term)
        wr(out, k, acc)


# ---------------------------------------------------------------------------
# Cariow--Cariowa schedule: three Walsh--Hadamard transforms, pointwise
# products, exact 1/N scaling, and sign corrections selected by the fixed masks
# ---------------------------------------------------------------------------
def fwht(e: Emitter, arr: dict[int, str], dim: int) -> None:
    # H[r,s] = (-1)^(r dot s), binary dot product modulo 2; H^2 = N I.
    length = 1
    while length < dim:
        # One butterfly stage per binary index bit, in increasing bit order.
        block = length << 1
        for base in range(0, dim, block):
            for o in range(length):
                lo = base + o
                up = lo + length
                left, right = arr[lo], arr[up]
                arr[lo] = e.add(left, right)
                arr[up] = e.sub(left, right)
        length <<= 1


def cc_transform_part(e: Emitter, x0: str, y0: str, x: Ptr, y: Ptr,
                      dim: int) -> dict[int, str]:
    # Start from the original coefficient vectors, then compute Hx and Hy.
    a = {i: (x0 if i == 0 else rd(x, i)) for i in range(dim)}
    b = {i: (y0 if i == 0 else rd(y, i)) for i in range(dim)}
    fwht(e, a, dim)
    fwht(e, b, dim)
    # Hc = (Hx) odot (Hy): one product per transform coordinate.
    for i in range(dim):
        a[i] = e.mul(a[i], b[i])
    # Recover c = H((Hx) odot (Hy))/N, using H^{-1} = H/N.
    fwht(e, a, dim)
    inv = f"0x1p-{dim.bit_length() - 1}"
    for i in range(dim):
        a[i] = e.mul(a[i], inv)
    return a


def cc_mul_straight(e: Emitter, out: Ptr, x: Ptr, y: Ptr, dim: int) -> None:
    # a[k] holds the unsigned convolution c_k; masks[k] encodes M_k.
    x0, y0 = "x0", "y0"
    a = cc_transform_part(e, x0, y0, x, y, dim)
    masks = cc_masks(dim)

    def xv(i: int) -> str:
        return x0 if i == 0 else rd(x, i)

    def yv(j: int) -> str:
        return y0 if j == 0 else rd(y, j)

    # z_k = epsilon_k (c_k - 2 sum_{i in M_k} x_i y_(i xor k)).
    for k in range(dim):
        mask = masks[k]
        modified = a[k]
        if mask:
            # Enumerate M_k and sum its products in increasing index order.
            bits = [i for i in range(dim) if (mask >> i) & 1]
            c = e.mul(xv(bits[0]), yv(bits[0] ^ k))
            for i in bits[1:]:
                c = e.add(c, e.mul(xv(i), yv(i ^ k)))
            # Each selected term changes sign by +t - 2t = -t.
            modified = e.sub(a[k], e.mul(c, "2.0"))
        # epsilon_0 = -1, epsilon_k = +1 otherwise; negate only the scalar row.
        wr(out, k, e.neg(modified) if k == 0 else modified)


# ---------------------------------------------------------------------------
# Function emission
# ---------------------------------------------------------------------------
def output_lines(out: Ptr, dim: int) -> list[str]:
    return [f"    out[{i}] = {out[0][i]};" for i in range(dim)]


def assemble(signature: str, params: list[str], e: Emitter,
             prologue: list[str], outputs: list[str]) -> list[str]:
    """Combine a signature, live temporaries, and output stores."""

    body = e.live_lines([line for line in outputs] + prologue)
    lines = [signature] + prologue + unused_casts(params, prologue + body + outputs)
    lines += body + outputs + ["}"]
    return lines


def emit_ql_mul(n: int) -> list[str]:
    e = Emitter()
    x, y = input_ptr("x", n), input_ptr("y", n)
    out: Ptr = ({}, 0)
    ws: Ptr = ({}, 0)
    if n > 1:
        quasilinear_cross(e, out, x, y, n, ws)
    reconstruct(e, out, x, y, n)
    return assemble(f"static inline void fastcd_ql_mul_{n}(double* restrict out, "
                    "const double* x, const double* y) {",
                    ["x", "y"], e, [], output_lines(out, n))


def emit_ql_cross(n: int) -> list[str]:
    e = Emitter()
