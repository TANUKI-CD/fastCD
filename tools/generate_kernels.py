HEADER = """/*
 * Generated by tools/generate_kernels.py.  Do not edit by hand.
 *
 * Included with FASTCD_REAL, FASTCD_ZERO, and FASTCD_NAME to instantiate the
 * same arithmetic for scalar coefficients or independent SIMD lanes.
 * This header intentionally has no include guard.
 *
 * Fixed schedules generated from the defining multiplication convention.
 * Direct leaves accumulate coordinate terms sequentially; their rounding
 * can differ from recursive grouping.  Outputs are stored last, so inputs
 * may coincide with each other.  Index zero of an alternating-product input
 * plane is never read.
 */
"""


# ---------------------------------------------------------------------------
# Basis sign of the standard Cayley--Dickson convention
#   (a,b)(c,d) = (ac - conj(d) b, d a + b conj(c)),  conj((a,b)) = (conj(a), -b)
# ---------------------------------------------------------------------------
@cache
def sign(dimension: int, i: int, j: int) -> int:
    """Return s with e_i e_j = s e_(i xor j) by the doubling recursion."""

    if dimension == 1:
        return 1
    half = dimension // 2
    if i < half and j < half:
        return sign(half, i, j)
    if i < half:
        return sign(half, j - half, i)
    if j < half:
        return (1 if j == 0 else -1) * sign(half, i - half, j)
    ip, jp = i - half, j - half
    return -(1 if jp == 0 else -1) * sign(half, jp, ip)


def cc_masks(dimension: int) -> list[int]:
    """Bit i of row k is set when x[i] y[i^k] needs the CC sign correction."""

    # M_k = {i : epsilon_k sigma_N(i,i xor k) < 0}; sign() supplies sigma_N.
    rows = []
    for k in range(dimension):
        # Account for the final scalar-row negation when selecting corrections.
        epsilon = -1 if k == 0 else 1
        mask = 0
        for i in range(dimension):
            if epsilon * sign(dimension, i, i ^ k) < 0:
                mask |= 1 << i
        rows.append(mask)
    return rows


# ---------------------------------------------------------------------------
# Straight-line emitter with symbolic memory
# ---------------------------------------------------------------------------
class Emitter:
    """Record straight-line operations; emit only those reaching an output."""

    def __init__(self) -> None:
        self.ops: list[tuple[str, str]] = []
        self.count = 0

    def _new(self, expr: str) -> str:
        self.count += 1
        t = f"t{self.count}"
        self.ops.append((t, expr))
        return t

    def op(self, a: str, o: str, b: str) -> str:
        return self._new(f"{a} {o} {b}")

    def add(self, a: str, b: str) -> str:
        return self.op(a, "+", b)

    def sub(self, a: str, b: str) -> str:
        return self.op(a, "-", b)

    def mul(self, a: str, b: str) -> str:
        return self.op(a, "*", b)

    def half(self, a: str) -> str:
        return self.op(a, "*", "0.5")

    def neg(self, a: str) -> str:
        return self._new(f"-{a}")

    def live_lines(self, roots: list[str]) -> list[str]:
        """Return declarations for operations that reach the given roots."""

        exprs = dict(self.ops)
        live: set[str] = set()
        stack = [t for root in roots for t in TEMP.findall(root)]
        while stack:
            t = stack.pop()
            if t in live:
                continue
            live.add(t)
            stack.extend(TEMP.findall(exprs[t]))
        return [f"    const double {t} = {expr};" for t, expr in self.ops
                if t in live]


TEMP = re.compile(r"\bt\d+\b")


def unused_casts(params: list[str], body: list[str]) -> list[str]:
    """Emit (void) casts for parameters the straight-line body never reads."""

    text = "\n".join(body)
    return [f"    (void){name};" for name in params
            if not re.search(rf"\b{name}\b", text)]


Ptr = tuple[dict[int, str], int]


def rd(p: Ptr, i: int) -> str:
    return p[0][p[1] + i]


def wr(p: Ptr, i: int, v: str) -> None:
    p[0][p[1] + i] = v


def off(p: Ptr, k: int) -> Ptr:
    return (p[0], p[1] + k)


def input_ptr(name: str, n: int) -> Ptr:
    return ({i: f"{name}[{i}]" for i in range(n)}, 0)


