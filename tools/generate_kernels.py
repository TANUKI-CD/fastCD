def emit_ql_complex(k: int) -> list[str]:
    e = Emitter()
    xr, xi = input_ptr("x_real", k), input_ptr("x_imag", k)
    yr, yi = input_ptr("y_real", k), input_ptr("y_imag", k)
    o_r: Ptr = ({}, 0)
    o_i: Ptr = ({}, 0)
    ws: Ptr = ({}, 0)
    complex_cross(e, o_r, o_i, xr, xi, yr, yi, k, ws)
    outputs = []
    for i in range(k):
        outputs.append(f"    out_real[{i}] = {o_r[0][i]};")
        outputs.append(f"    out_imag[{i}] = {o_i[0][i]};")
    return assemble(f"static inline void fastcd_ql_complex_cross_{k}("
                    "double* restrict out_real, double* restrict out_imag, "
                    "const double* x_real, const double* x_imag, "
                    "const double* y_real, const double* y_imag) {",
                    ["x_real", "x_imag", "y_real", "y_imag"], e, [], outputs)


