"""Direct CD schedules using the coefficient operations of each packed backend."""

import re
from functools import cache


@cache
def sign(dimension: int, i: int, j: int) -> int:
    """Return s with e_i e_j = s e_(i xor j) by the doubling recursion."""

    if dimension == 1:
        return 1
    half = dimension // 2
    if i < half and j < half:
        return sign(half, i, j)
    if i < half:
        return sign(half, j - half, i)
    if j < half:
        return (1 if j == 0 else -1) * sign(half, i - half, j)
    ip, jp = i - half, j - half
    return -(1 if jp == 0 else -1) * sign(half, jp, ip)


def value_schedule() -> str:
    """Return the direct recursion over register values shared by all backends."""

    text = """/*
 * Generated by tools/finite/generate_finite_backends.py from
 * tools/finite/finite_direct.py; do not edit by hand.
 *
 * The defining four-product CD recursion over a backend's exact value
 * operations VADD, VSUB, VMUL and VZERO. Records of up to eight coordinates
 * are unrolled, and larger records recurse with 2n-16 words of scratch. The
 * template has no include guard.
 */
// Evaluate (a,b)(c,d) = (ac - conjugate(d)b, da + b conjugate(c)) on values
static FASTCD_FF_UNUSED void FASTCD_FF_NAME(direct_values)(Word* restrict out,
 const Word* x,const Word* y,size_t n,Word* restrict work,
 const Context* restrict ctx) {
 // Unroll every output coordinate through eight coordinates
 switch(n) {
"""
    for n in (1, 2, 4, 8):
        text += f"case {n}:\n"
        for k in range(n):
            expr = f"VMUL(x[0],y[{k}])"
            for i in range(1, n):
                op = "VADD" if sign(n, i, i ^ k) > 0 else "VSUB"
                expr = f"{op}({expr},VMUL(x[{i}],y[{i ^ k}]))"
            text += f"out[{k}]={expr};\n"
        text += "return;\n"
    return (
        text
        + """default:break;
 }
 // One conjugated half, one partial product, then the children's scratch
 size_t h=n/2;
 Word* temp=work;Word* product=temp+h;Word* child=product+h;
 // Lower half: ac - conjugate(d)b
 FASTCD_FF_NAME(direct_values)(out,x,y,h,child,ctx);
 temp[0]=y[h];for(size_t i=1;i<h;i++)temp[i]=VSUB(VZERO,y[h+i]);
 FASTCD_FF_NAME(direct_values)(product,temp,x+h,h,child,ctx);
 for(size_t i=0;i<h;i++)out[i]=VSUB(out[i],product[i]);
 // Upper half: da + b conjugate(c)
 FASTCD_FF_NAME(direct_values)(out+h,y+h,x,h,child,ctx);
 temp[0]=y[0];for(size_t i=1;i<h;i++)temp[i]=VSUB(VZERO,y[i]);
 FASTCD_FF_NAME(direct_values)(product,x+h,temp,h,child,ctx);
 for(size_t i=0;i<h;i++)out[h+i]=VADD(out[h+i],product[i]);
}
"""
    )


def packed_schedule(lanes, scalar_bits, prefix, ternary=False):
    """Return the prototype and body of the packed direct schedule of one backend.

    A packed record holds `points` coefficients per CD coordinate in adjacent
    lanes. Leaves fill one vector, and larger records recurse as in the value
    schedule; with every lane a separate coordinate, the value schedule applies.
    """
    bits = 512 if prefix == "_mm512" else 256 if prefix == "_mm256" else 128
    coef = "Coef" if ternary or scalar_bits == 8 else f"uint{scalar_bits}_t"

    def const(values, width=scalar_bits):
        if prefix == "_mm512" and width in (8, 16):
            return (
                f"{prefix}_set_epi{width}(" + ",".join(map(str, reversed(values))) + ")"
            )
        return f"{prefix}_setr_epi{width}(" + ",".join(map(str, values)) + ")"

    def perm(value, indices):
        if scalar_bits == 32 and bits == 128:
            imm = sum(k << (2 * j) for j, k in enumerate(indices))
            return f"_mm_shuffle_epi32({value},{imm})"
        if scalar_bits == 32 or (scalar_bits == 16 and bits == 512):
            name = "permutexvar" if bits == 512 else "permutevar8x32"
            if bits == 256:
                return f"_mm256_permutevar8x32_epi32({value},{const(indices)})"
            return f"{prefix}_{name}_epi{scalar_bits}({const(indices)},{value})"
        # Byte shuffles act within 128-bit quarters, and both permutations the
        # leaf uses (XOR and repeated point groups) map whole quarters
        byte_indices = [
            i * (scalar_bits // 8) + b for i in indices for b in range(scalar_bits // 8)
        ]
        if bits == 512:
            quarters = [byte_indices[k] // 16 for k in range(0, 64, 16)]
            word_indices = [q * 4 + j for q in quarters for j in range(4)]
            if word_indices != list(range(16)):
                value = f"_mm512_permutexvar_epi32({const(word_indices, 32)},{value})"
        elif bits == 256:
            lo, hi = byte_indices[0] // 16, byte_indices[16] // 16
            if (lo, hi) != (0, 1):
                value = f"_mm256_permute2x128_si256({value},{value},{lo + 16 * hi})"
        return (
            f"{prefix}_shuffle_epi8({value},{const([i % 16 for i in byte_indices], 8)})"
        )

    def word_perm(value, indices):
        if ternary:
            return (
                "(Word){"
                + perm(value + ".one", indices)
                + ","
                + perm(value + ".two", indices)
                + "}"
            )
        return perm(value, indices)

    def blend(left, right, negative):
        if bits == 512:
            mask = sum(1 << j for j, v in enumerate(negative) if v)

            def one(a, b):
                return f"_mm512_mask_blend_epi{scalar_bits}(UINT64_C({mask}),{a},{b})"
        else:
            mask = const(
                [
                    -1 if negative[k // (scalar_bits // 8)] else 0
                    for k in range(bits // 8)
                ],
                8,
            )

            def one(a, b):
                return f"{prefix}_blendv_epi8({a},{b},{mask})"

        if ternary:
            return (
                "(Word){"
                + one(left + ".one", right + ".one")
                + ","
                + one(left + ".two", right + ".two")
                + "}"
            )
        return one(left, right)

    ld = "ld(a)" if ternary else f"{prefix}_loadu_si{bits}((const void*)a)"
    st = "st(a,v);" if ternary else f"{prefix}_storeu_si{bits}((void*)a,v);"
    text = f"""
// Load one vector of packed coefficients
static inline Word direct_load(const {coef}* a){{return {ld};}}
// Store one vector of packed coefficients
static inline void direct_store({coef}* a,Word v){{{st}}}
"""
    for points in (1 << k for k in range(lanes.bit_length() - 1)):
        count = lanes // points
        text += f"""// Multiply records of {count} coordinates with {points} lanes each in one vector
static void direct_leaf{points}({coef}* out,const {coef}* x,
 const {coef}* y,const Context* ctx){{
 // Some backends' value operations ignore the context
 (void)ctx;Word a=direct_load(x),b=direct_load(y),sum;
 // Sum the signed products of each lane permutation
"""
        for i in range(count):
            xidx = [i * points + k % points for k in range(lanes)]
            yidx = [k ^ (i * points) for k in range(lanes)]
            negative = [sign(count, i, i ^ (k // points)) < 0 for k in range(lanes)]
            text += (
                "{Word left="
                + word_perm("a", xidx)
                + ",right="
                + word_perm("b", yidx)
                + ";Word term=VMUL(left,right);\n"
            )
            if any(negative):
                text += (
                    "Word negated=VSUB(VZERO,term);term="
                    + blend("term", "negated", negative)
                    + ";\n"
                )
            text += ("sum=term;" if i == 0 else "sum=VADD(sum,term);") + "}\n"
        text += "direct_store(out,sum);}\n"
    text += f"""
// Evaluate the defining recursion on records with several lanes per coordinate
static void packed_direct({coef}* restrict out,const {coef}* x,const {coef}* y,
 size_t n,{coef}* restrict work,size_t points,const Context* ctx){{
 // With a whole vector per coordinate, run the value schedule
 if(points=={lanes}){{FASTCD_FF_NAME(direct_values)((Word*)out,(const Word*)x,
  (const Word*)y,n,(Word*)work,ctx);return;}}
 // Records that fill one vector are leaves
 if(n=={lanes}/points){{switch(points){{
"""
    for points in (1 << k for k in range(lanes.bit_length() - 1)):
        text += f"case {points}:direct_leaf{points}(out,x,y,ctx);return;\n"
    text += f"""default:__builtin_trap();}}}}
 // One conjugated half, one partial product, then the children's scratch
 size_t h=n/2,size=h*points;
 {coef}* temp=work;{coef}* product=temp+size;{coef}* child=product+size;
 // Lower half: ac - conjugate(d)b, keeping the scalar coordinate of d
 packed_direct(out,x,y,h,child,points,ctx);
 for(size_t i=0;i<size;i+={lanes}){{Word value=direct_load(y+size+i);
  direct_store(temp+i,VSUB(VZERO,value));}}
 memcpy(temp,y+size,points*sizeof(*temp));
 packed_direct(product,temp,x+size,h,child,points,ctx);
 for(size_t i=0;i<size;i+={lanes}){{Word a=direct_load(out+i),b=direct_load(product+i);
  direct_store(out+i,VSUB(a,b));}}
 // Upper half: da + b conjugate(c), keeping the scalar coordinate of c
 packed_direct(out+size,y+size,x,h,child,points,ctx);
 for(size_t i=0;i<size;i+={lanes}){{Word value=direct_load(y+i);
  direct_store(temp+i,VSUB(VZERO,value));}}
 memcpy(temp,y,points*sizeof(*temp));
 packed_direct(product,x+size,temp,h,child,points,ctx);
 for(size_t i=0;i<size;i+={lanes}){{Word a=direct_load(out+size+i),b=direct_load(product+i);
  direct_store(out+size+i,VADD(a,b));}}
}}
"""
    prototype = f"static void packed_direct({coef}*,const {coef}*,const {coef}*,size_t,{coef}*,size_t,const Context*);\n"
    return prototype, text


def add_direct(source, name):
    """Add the direct schedule to one backend's generated source.

    The backend's Context gains a direct flag, every complete-call wrapper sets
    it from FASTCD_FF_SCHEDULE_DIRECT, and each packed CD root branches to the
    packed direct schedule when the flag is set.
    """
    ternary = name.startswith("finite_ternary")
    if name.startswith("finite_mont"):
        lanes = int(name.removesuffix(".c").split("_")[-1])
        scalar_bits = 32
        prefix = {4: "_mm", 8: "_mm256", 16: "_mm512"}[lanes]
    else:
        scalar_bits = (
            int(name.removesuffix(".c").split("_")[-1])
            if ternary
            else 8
            if name == "finite_byte.c"
            else 16
        )
        lanes = (
            512 // scalar_bits
            if ternary
            or name in ("finite_byte.c", "finite_medium_bar.c", "finite_medium_mont.c")
            else int(name.removesuffix(".c").split("_")[-1])
        )
        prefix = {128: "_mm", 256: "_mm256", 512: "_mm512"}[lanes * scalar_bits]
    roots = re.compile(r"static void (\w+(?:_prime_cd|_cd\d+|_root))\([^;{}]*\)\s*\{")
    prototype, body = (
        packed_schedule(lanes, scalar_bits, prefix, ternary)
        if roots.search(source)
        else ("", "")
    )
    source = re.sub(
        r"(typedef\s+struct\s*\{[^{}]*)(\}\s*Context;)", r"\1int direct;\n\2", source
    )
    # Initialize the direct flag in every Context literal, including loop helpers
    for match in reversed(list(re.finditer(r"Context c\s*=\s*\{", source))):
        end = source.index("};", match.end())
        source = source[:end] + ",0" + source[end:]
    marker = '#include "finite_value.h"'
    source = source.replace(
        marker,
        "#define FASTCD_FF_IS_DIRECT(ctx) ((ctx)->direct)\n"
        + marker
        + "\n"
        + prototype,
    )
    # Complete-call wrappers that own a Context set the flag from the schedule
    pattern = re.compile(
        r"(?:static )?(?:void|int) (\w+)\([^;{}]*\bint loop\b[^;{}]*\)\s*\{"
    )
    for match in reversed(list(pattern.finditer(source))):
        start = match.end()
        depth, end = 1, start
        while depth:
            depth += (source[end] == "{") - (source[end] == "}")
            end += 1
        content = source[start : end - 1]
        init = re.search(r"Context c\s*=.*?;", content, re.S)
        if not init:
            continue
        content = (
            content[: init.end()]
            + "\n// Run the defining recursion when the caller asks for direct\n"
            + "c.direct=(loop==FASTCD_FF_SCHEDULE_DIRECT);if(c.direct)loop=0;\n"
            + content[init.end() :]
        )
        # Encoded Montgomery entry points rebuild their Context, so the flag
        # is passed to them as an argument
        content = re.sub(
            r"(fastcd_ff_points\d+_cd_encoded\([^;]+)(\);)", r"\1,c.direct\2", content
        )
        source = source[:start] + content + source[end - 1 :]
    source = re.sub(
        r"(void fastcd_ff_points\d+_cd_encoded\([^{};]+size_t points)\)\s*\{",
        r"\1,int direct){",
        source,
    )
    source = re.sub(
        r"(void fastcd_ff_points\d+_cd_encoded\([^{};]+size_t)\);", r"\1,int);", source
    )
    # Whitespace is still the compact generator format at this stage
    encoded = re.compile(
        r"(void fastcd_ff_points\d+_cd_encoded\([^{}]+)\{([^{}]*Context c\s*=[^;]+;)"
    )
    source = encoded.sub(r"\1{\2c.direct=direct;", source)
    # Packed CD roots have uniform coefficient arrays, and their function name
    # gives the number of lanes per coordinate
    for match in reversed(list(roots.finditer(source))):
        signature = match.group(0)
        names = [
            re.search(r"(\w+)\s*$", v).group(1)
            for v in signature[signature.index("(") + 1 : signature.rindex(")")].split(
                ","
            )
        ]
        out, x, y, n, work, ctx = names
        points_match = re.search(r"_cd(\d+)$", match.group(1))
        points = points_match.group(1) if points_match else "1"
        call = (
            f"\n// Run the packed direct schedule when the caller asks for direct\nif({ctx}->direct){{packed_direct("
            f"{out},{x},{y},{n},{work},{points},{ctx});return;}}\n"
        )
        source = source[: match.end()] + call + source[match.end() :]
    return source + "\n" + body
