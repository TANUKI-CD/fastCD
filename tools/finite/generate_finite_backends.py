ATTRIBUTE = re.compile(r"__attribute__\(\((?:[^()]|\([^()]*\))*\)\)")


def describe_functions(text):
    """Insert the role comment above every uncommented function definition."""

    lines = text.split("\n")
    output = []
    skip = 0
    for i, line in enumerate(lines):
        # Lines that continue a signature already described are copied as they are
        if skip:
            skip -= 1
            output.append(line)
            continue
        start = (
            line[:1].isalpha()
            and not line.startswith(("typedef", "struct", "union", "enum"))
            and not (output and output[-1].lstrip().startswith(("//", "*")))
            and not (output and output[-1].rstrip().endswith("*/"))
        )
        if start:
            signature = ""
            count = 0
            # Read the signature up to its opening brace or semicolon
            while count < 8 and i + count < len(lines):
                later = lines[i + count]
                signature += " " + later
                if "{" in later or later.rstrip().endswith(";"):
                    break
                count += 1
            head = ATTRIBUTE.sub("", signature)
            body = head.find("{")
            paren = head.find("(")
            if 0 <= paren < body and "=" not in head[:paren] and ";" not in head[:body]:
                name = head[:paren].split()[-1].lstrip("*")
                for pattern, description in ROLES:
                    match = re.fullmatch(pattern, name)
                    if match:
                        number = next((g for g in match.groups() if g), "")
                        text = re.sub(r"\b1 lanes\b", "1 lane", description.format(number))
                        output.append("// " + text)
                        skip = count
                        break
                else:
                    raise SystemExit(f"no description for generated function {name}")
        output.append(line)
    return "\n".join(output)


def emit(name, source):
    """Apply portability fixes and emit a formatted, private backend unit."""

    # Private exported definitions have matching hidden declarations in the
    # internal header, and every other helper has translation-unit linkage
    source = source.replace('"finite_value_schedule.h"', '"finite_value.h"')
    source = add_direct(source, name)
    source = source.replace("ri=1,b=r,e=prime-2", "ri=1,power_base=r,e=prime-2")
    source = source.replace("ri,b,&p->field", "ri,power_base,&p->field")
    source = source.replace(
        "b=fastcd_ff_prime_mul(b,b,&p->field)",
        "power_base=fastcd_ff_prime_mul(power_base,power_base,&p->field)",
    )
    source = source.replace(
        ",coefficients,quotient,rv,rq,",
        ",(const uint32_t (*)[12])coefficients,(const uint32_t (*)[12])quotient,rv,rq,",
    )
    source = re.sub(
        r"_mm256_i32gather_epi32\(([^,]+),",
        lambda m: "_mm256_i32gather_epi32((const int*)(" + m.group(1) + "),",
        source,
    )
    source = source.replace("Word acc[4];", "Word acc[4]={0};")
    if name == "finite_shuffle_32.c":
        source = source.replace(
            "Word a=_mm512_loadu_si512((const void*)(f+i)),b=_mm512_loadu_si512((const void*)(g+i));",
            "Word left=_mm512_loadu_si512((const void*)(f+i)),right=_mm512_loadu_si512((const void*)(g+i));",
        )
        source = source.replace(
            "Word s=half(add(a,b,&c),&c),t=half(sub(a,b,&c),&c);",
            "Word s=half(add(left,right,&c),&c),t=half(sub(left,right,&c),&c);",
        )
    source = re.sub(
        r"\bstatic inline\b", "static inline __attribute__((unused))", source
    )
    if name.startswith("finite_ternary"):
        source = source.replace(
            "Word a=ld(x+i),b=ld(y+i);dot=add(dot,multiply(a,b));",
            "Word left=ld(x+i),right=ld(y+i);dot=add(dot,multiply(left,right));",
        )
        source = source.replace(
            "multiply(alpha,b),multiply(beta,a)",
            "multiply(alpha,right),multiply(beta,left)",
        )
        source = source.replace(
            "Coef a=f[i],b=g[i];f[i]=sn(sa(a,b));u[i]=sn(ss(a,b));",
            "Coef left=f[i],right=g[i];f[i]=sn(sa(left,right));u[i]=sn(ss(left,right));",
        )
        source = source.replace(";if(input", ";\n  if(input").replace(
            ";if(output", ";\n  if(output"
        )
    source = re.sub(r"uint32_t\*\s*(out|work)\b", r"uint32_t* restrict \1", source)
    source = re.sub(
        r"\(loop\?(\d+):(\d+)\)", lambda m: f"(loop?{m[1]}u:{m[2]}u)", source
    )
    alias = ""
    if "uint16_t" in source:
        source = source.replace("uint16_t", "FastCDFFPacked16")
        alias = "// Smaller internal lanes share caller-owned uint32_t scratch\ntypedef uint16_t FastCDFFPacked16 __attribute__((may_alias));\n"
    target = OUT / name
    # Packed lanes are selected only after characteristic and rank range checks,
    # so their deliberate narrowing conversions are exempt, and the remaining
    # warnings (including bounds, shadows and prototypes) stay errors
    diagnostics = '#if defined(__GNUC__) || defined(__clang__)\n#pragma GCC diagnostic ignored "-Wconversion"\n#pragma GCC diagnostic ignored "-Wsign-conversion"\n#endif\n'
    content = describe_functions(format_c(BANNER + diagnostics + alias + source))
    if not target.exists() or target.read_text() != content:
        target.write_text(content)


def main():
    """Assemble selected backends and shared schedules from source templates."""

    OUT.mkdir(exist_ok=True)
    # Every backend includes the same direct template beside finite_value.h
    direct = ROOT / "src/finite/direct_value.h"
    direct_text = format_c(value_schedule())
    if not direct.exists() or direct.read_text() != direct_text:
        direct.write_text(direct_text)
    with tempfile.TemporaryDirectory(prefix="fastcd-finite-codegen-") as td:
        work = Path(td)
        for module in (
            mont,
            prime,
            points,
            differences,
            shuffle,
            short,
            small,
            slice_vector,
            slice_wide,
            medium,
            ternary,
            byte,
        ):
            module.WORK = work
        for L, bits, p, flags in (
            (4, 128, "_mm", ["-msse4.1"]),
            (8, 256, "_mm256", ["-mavx2"]),
            (16, 512, "_mm512", ["-mavx512f", "-mavx512dq"]),
        ):
            args = (L, bits, p, flags)
            mont.generate(*args, fast=True, values=True, build=False)
            prime.append(*args, build=False)
            points.generate(*args, build=False)
            differences.generate(
                *args, multipoint=True, build=False, vector_packing=(L == 16)
            )
            text = (work / f"multi{L}.c").read_text()
            base = (work / f"value{L}.c").read_text()
            text += "\n" + base[base.index(f"void value{L}_prime_tensor(") :]
            diff_name = f"tile{L}" if L == 16 else f"hybrid{L}"
            diff = (work / f"{diff_name}.c").read_text()
            text += "\n" + diff[diff.index(f"static inline void {diff_name}_store2(") :]
            text = (
                text.replace(f"value{L}", f"fastcd_ff_mont{L}")
                .replace(f"multi{L}", f"fastcd_ff_points{L}")
                .replace(diff_name, f"fastcd_ff_extension{L}")
            )
            if L == 16:
                text += (
                    "\n" + (ROOT / "tools/finite/finite_prepare_linear.h").read_text()
                )
            emit(f"finite_mont_{L}.c", text)
        for L, bits, p, flags in (
            (8, 128, "_mm", ["-msse4.1"]),
            (16, 256, "_mm256", ["-mavx2"]),
            (32, 512, "_mm512", ["-mavx512f", "-mavx512bw"]),
        ):
            short.generate(L, bits, p, flags, False, build=False)
            short_text = (
                (work / f"shortbar{L}.c")
                .read_text()
                .replace(f"shortbar{L}", f"fastcd_ff_short{L}")
            )
            if L == 32:
                short_text = short_prime(short_text, "fastcd_ff_short32", False)
            emit(f"finite_short_{L}.c", short_text)
            if L != 32:
                shuffle.generate(L, bits, p, flags, build=False)
                emit(
                    f"finite_shuffle_{L}.c",
                    (work / f"shuffle{L}.c")
                    .read_text()
                    .replace(f"shuffle{L}", f"fastcd_ff_small{L}"),
                )
        small.generate(build=False)
        small_text = (work / "sm32.c").read_text().replace("sm32", "fastcd_ff_small32")
        shuffle.generate(32, 512, "_mm512", ["-mavx512f", "-mavx512bw"], build=False)
        plain = (work / "shuffle32.c").read_text()
        first = plain.index("void shuffle32_tensor(")
        last = plain.index("static uint32_t horizontal(", first)
        plain = (
            plain[first:last]
            .replace("shuffle32_tensor", "fastcd_ff_small32_plain_tensor")
            .replace("shuffle32", "fastcd_ff_small32")
        )
        plain = plain.replace(
            "project(out,result,size,d,first,rank,output,&c)",
            "project(out,(const uint16_t*)result,size,d,first,rank,32,output,&c)",
        )
        emit(
            "finite_shuffle_32.c",
            small_text
            + "\n"
            + plain
            + "\n"
            + (ROOT / "tools/finite/finite_prepare_small.h").read_text(),
        )
        slice_vector.generate(build=False)
        for bits in (16, 32, 64):
            ternary.generate(bits, build=False)
            emit(
                f"finite_ternary_{bits}.c",
                (work / f"tri{bits}.c")
                .read_text()
                .replace(f"tri{bits}", f"fastcd_ff_ternary{bits}"),
            )
        byte.generate(build=False)
        emit(
            "finite_byte.c",
            (work / "byte64.c").read_text().replace("byte64", "fastcd_ff_byte64"),
        )
        short.generate(
            32, 512, "_mm512", ["-mavx512f", "-mavx512bw"], True, build=False
        )
        for mode in (False, True):
            medium.generate(mode, build=False, vector_packing=True)
            name = "medium_mont" if mode else "medium_bar"
            source_name = "tilemont" if mode else "tilebar"
            emit(
                f"finite_{name}.c",
                (work / f"{source_name}.c")
                .read_text()
                .replace(source_name, f"fastcd_ff_{name}"),
            )
        for name in ("finite_short_mont.c", "finite_ternary.c"):
            obsolete = OUT / name
            if obsolete.exists():
                obsolete.unlink()
    maps.generate()
    value = (ROOT / "tools/finite/finite_value_schedule.h").read_text()
    value = value.replace(
        "Experimental register-value specialization", "Register-value specialization"
    )
    value = value.replace(
        "static void FASTCD_FF_NAME", "static FASTCD_FF_UNUSED void FASTCD_FF_NAME"
    )
    value = format_c(value)
    target = ROOT / "src/finite/finite_value.h"
    if not target.exists() or target.read_text() != value:
        target.write_text(value)
    for name in ("src/finite/finite_maps.h", "src/finite/generated/finite_maps.c"):
        target = ROOT / name
        target.write_text(format_c(target.read_text()))


if __name__ == "__main__":
    main()
