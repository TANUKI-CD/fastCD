ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/finite/generated"
BANNER = """/*
 * Generated by tools/finite/generate_finite_backends.py; do not edit by hand.
 *
 * Fixed coefficient encodings around the shared direct and quasilinear CD
 * schedules. Public buffers hold canonical polynomial-basis uint32 coefficients,
 * while packed lanes and Montgomery values are private temporaries in caller
 * scratch. The dispatcher checks CPU features, coefficient ranges and scratch
 * capacity before entering these private functions, and the field-specific
 * evaluation and reconstruction maps are prepared inside the complete call.
 * To change this file, change the generator or its templates and regenerate.
 */
#include "finite_backend.h"
"""


